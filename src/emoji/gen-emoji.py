#!/usr/bin/env python3
"""gen-emoji.py EMOJI_TEST OUT -- the emoji panel's table (sg-emoji), from Unicode's
emoji-test.txt (Debian's unicode-data: /usr/share/unicode/emoji/emoji-test.txt).

Every fully-qualified emoji, in CLDR order (the order Unicode recommends for a
keyboard's palette), with its CLDR short name for search and its group (the
panel's categories). Skin-tone variants (U+1F3FB..1F3FF) are left out: the
panel shows each emoji once, in its default (yellow) tone.

Copyright (C) 2026 Stained Glass OS contributors
SPDX-License-Identifier: AGPL-3.0-or-later
"""
import sys

GROUPS = ["Smileys & Emotion", "People & Body", "Animals & Nature", "Food & Drink",
          "Travel & Places", "Activities", "Objects", "Symbols", "Flags"]
TONES = set(range(0x1F3FB, 0x1F400))


def c_wstr(cps):
    out = []
    for cp in cps:
        if cp > 0xFFFF:
            cp -= 0x10000
            out += [0xD800 + (cp >> 10), 0xDC00 + (cp & 0x3FF)]
        else:
            out.append(cp)
    return 'L"' + "".join("\\x%04x" % u for u in out) + '"'


def main(src, dst):
    group = None
    rows = []
    with open(src, encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            if line.startswith("# group:"):
                name = line.split(":", 1)[1].strip()
                group = GROUPS.index(name) if name in GROUPS else None
                continue
            if not line or line.startswith("#") or group is None:
                continue
            code, rest = line.split(";", 1)
            if "fully-qualified" not in rest.split("#", 1)[0]:
                continue
            cps = [int(c, 16) for c in code.split()]
            if any(c in TONES for c in cps):
                continue
            # "# 😀 E1.0 grinning face": the name after the version
            comment = rest.split("#", 1)[1].strip().split(" ", 2)
            name = comment[2] if len(comment) > 2 else ""
            name = name.replace("\\", "").replace('"', "")
            rows.append((c_wstr(cps), name.encode("ascii", "replace").decode(), group))
    with open(dst, "w") as f:
        f.write("/* generated by src/emoji/gen-emoji.py from Unicode's emoji-test.txt */\n")
        f.write("static const struct emoji_entry emoji_table[] = {\n")
        for chars, name, grp in rows:
            f.write('    { %s, "%s", %d },\n' % (chars, name, grp))
        f.write("};\n")
    print("%s: %d emoji" % (dst, len(rows)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
